// Helper function to build regional dictionary with common translations and landing page
function createRegionalDict(
  commonOverrides: Partial<typeof en.common>,
  landingOverrides: Partial<typeof en.landing>,
  modules?: RegionalModules
): typeof en {
  return {
    ...en,
    common: {
      ...en.common,
      ...commonOverrides,
      ...(modules?.commonExtra || {}),
    },
    landing: {
      ...en.landing,
      ...landingOverrides,
    },
    auth: {
      ...en.auth,
      ...(modules?.auth || {}),
    },
    patient: {
      ...en.patient,
      ...(modules?.patient || {}),
    },
    reviewer: {
      ...en.reviewer,
      ...(modules?.reviewer || {}),
    },
    admin: {
      ...en.admin,
      ...(modules?.admin || {}),
    },
  };
}

